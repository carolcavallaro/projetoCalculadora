# --- PROJETO DE CALCULADORA PARA TREINAR GIT & GITHUB ---

soma1 = int(input('Digite um número para somar: '))
soma2 = int(input('Digite outro número para somar: '))
soma = soma1 + soma2
print(f'O resultado é: {soma}')

print('Agora, vamos subtrair.')
subtracao1 = int(input('Digite um número: '))
subtracao2 = int(input('Digite outro número: '))
subtracao = subtracao1 - subtracao2
print(f'O resultado é: {subtracao}')

